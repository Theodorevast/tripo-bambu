// 品牌标志：一圈圆、V 和 T 的外轮廓。
// V、T 的轮廓和启动画面天体仪中心的细金线标志（v2-ui，index.html 里的 .bl-v / .bl-t 两条 path）是同一份数据：
// 从 public/brand/tripo-logo.png 描下来的，原来的坐标以标志方块的中心为原点、方块边长 700、y 朝下。
// 这里换成「圆的半径 = 1、y 朝上」：方块的半边长 350 对应 0.8（字形落在圆里，占圆的直径一半左右）。
// 开场星尘拼标志（homeGalaxy.ts：细金线一笔一笔描出来 + 少量星尘点缀）用它；线宽、颜色和启动画面一致

export type Pt = [number, number];

// 启动画面那份原始坐标（700 的方块、y 朝下），首尾相连的闭合轮廓
const V_SVG: Pt[] = [
  [-183.0, -167.5], [-26.0, 99.5], [-15.5, 110.0], [-7.5, 113.0], [5.5, 113.0], [14.5, 109.0], [23.0, 100.5], [119.5, -64.0],
  [194.0, -63.5], [152.0, 7.5], [60.0, 164.5], [45.5, 181.0], [25.5, 193.0], [0.5, 198.0], [-18.5, 196.0], [-39.5, 187.0],
  [-46.5, 182.0], [-63.0, 163.5], [-208.0, -85.5], [-212.0, -104.5], [-210.0, -126.5], [-201.0, -147.5], [-194.0, -157.5],
];
const T_SVG: Pt[] = [
  [-129.0, -179.5], [144.5, -180.0], [169.5, -171.0], [180.5, -163.0], [195.0, -145.5], [201.0, -132.5], [203.5, -118.0], [91.5, -118.0],
  [60.0, -65.5], [10.0, 19.5], [1.5, 25.0], [-8.5, 23.0], [-16.0, 14.5], [-38.0, -24.5], [16.0, -117.5], [-92.5, -118.0],
];

const S = 0.8 / 350;
const toMark = (p: Pt): Pt => [p[0] * S, -p[1] * S];

export const BRAND_MARK = {
  ring: 1, // 圆的半径
  vOutline: V_SVG.map(toMark), // V 的外轮廓（闭合：最后一个点连回第一个）
  tOutline: T_SVG.map(toMark), // T 的外轮廓（闭合）
  color: '#d8c08e', // Champagne gold
  lineWidthPx: 1.3, // 线宽（CSS 像素），和启动画面一样
};

// 闭合轮廓变成首尾相连的折线（沿着走一圈用）
export function closed(outline: Pt[]): Pt[] {
  return [...outline, outline[0]];
}
